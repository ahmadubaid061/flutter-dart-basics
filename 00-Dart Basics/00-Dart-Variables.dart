void main(){
  // ---------------------string data type
  String name="Ubaid";
  print("my name is $name");
  // ---------------------integer data type
  int age=24;
  print("my age is  $age");
  // ---------------------double data type
  double gpa=3.55;
  print("my cgpa is $gpa");
  // ---------------------var data type (it has a global scope)
  var phone=03139215242;
  print("my phone is $phone");
  // ---------------------dynamic data type (its content can be changes)
  dynamic currentCity='Islamabad';
  print("my current City is $currentCity");
  // ---------------------const data type  (its content cannot be changed)
  const rollNo=11;
  print("my roll No is $rollNo");
}